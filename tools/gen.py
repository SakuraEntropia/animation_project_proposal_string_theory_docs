T, SB = D['top'], D['sub']
O = os.path.join(ROOT, '.build', 'out')
os.makedirs(O, exist_ok=True)

BARE = re.compile(r'^\d+\.?\s*$')
SUBNUM = re.compile(r'^\d+\.\d+\s')

def _clean(v):
    v = [x for x in v if not BARE.match(x) and not SUBNUM.match(x)]
    while v and v[0] == '': v.pop(0)
    while v and v[-1] == '': v.pop()
    return v

def top(n, drop_first=True):
    v = list(T[str(n)])
    if drop_first and v: v = v[1:]
    return '\n'.join(_clean(v))

def sub(key, drop_first=True):
    v = list(SB[key])
    if drop_first and v: v = v[1:]
    return '\n'.join(_clean(v))

def joined(*idx, key='top'):
    src = T if key == 'top' else SB
    out = []
    for i in idx:
        out.extend(x.strip() for x in src[str(i)] if x.strip())
    return ' '.join(out)

def enum(block):
    groups, buf = [], []
    for ln in block.split('\n'):
        if not ln.strip():
            if buf: groups.append(buf); buf = []
            continue
        buf.append(ln.strip())
    if buf: groups.append(buf)
    items = [re.sub(r'^\d+\.\s*', '', ' '.join(g)) for g in groups]
    return '\n\n'.join('- ' + t for t in items)

def hdr(src_, form):
    return f"<!--\n  SOURCE: {src_}\n  FORM:   {form}\n-->\n\n"

W = lambda name, text: open(f'{O}/{name}', 'w').write(text)

